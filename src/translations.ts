export function translateText(text: string, lang: LanguageCode): string {
  if (lang === 'id') return text;

  const trimmed = text.trim();
  const lower = trimmed.toLowerCase();

  // 1. Direct dictionary match
  if (bilingualDictionary[trimmed]) {
    return bilingualDictionary[trimmed][lang] || bilingualDictionary[trimmed]['en'];
  }

  // 2. Case-insensitive lookup
  for (const [key, val] of Object.entries(bilingualDictionary)) {
    if (key.toLowerCase() === lower) {
      return val[lang] || val['en'];
    }
  }

  // 3. Dynamic search & replace for common status tags and categories
  let result = trimmed;
  
  // Normalize status for translation lookup
  const normalized = result.toUpperCase();
  const statusMap: Record<string, string> = {
    'VERIFIED': 'Verified',
    'PENDING': 'Pending',
    'APPROVED': 'Approved',
    'REJECTED': 'Rejected',
    'ACTIVE': 'Active',
    'UNPAID': 'Unpaid',
    'PAID': 'Paid',
    'CONFIRMED': 'Confirmed'
  };

  if (statusMap[normalized]) return statusMap[normalized];
  
  // Basic vocabulary mapping for common words
  const wordMap: Record<string, string> = {
    "Sertifikat": "Certificate",
    "Terbit": "Issued",
    "Daftar": "Register",
    "Kembali": "Back",
    "Unduh": "Download",
    "Semua": "All",
    "Waktu": "Time",
    "Lokasi": "Location",
    "Nama": "Name",
    "Telepon": "Phone",
    "Status": "Status",
    "Batal": "Cancel",
    "Simpan": "Save",
    "Ubah": "Edit",
    "Cari": "Search",
    "Unduh Dokumen": "Download Document",
    "Verifikasi": "Verify",
    "Hukum": "Legal",
    "Keanggotaan": "Membership",
    "Anggota": "Member",
    "Pendaftaran": "Registration",
    "Hubungi Kami": "Contact Us"
  };

  if (lang === 'en') {
    if (wordMap[result]) return wordMap[result];
  }

  return result;
}
